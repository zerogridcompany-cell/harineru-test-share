def wbr(t):
    out = []
    parts = re.split(r"(<[^>]+>)", t)
    for p in parts:
        if p.startswith("<"):
            out.append(p); continue
        s = ""
        for i, c in enumerate(p):
            s += c
            rest = p[i + 1:]
            tail = re.sub(r"[、。！？」）』\s]", "", rest)
            if len(tail) <= 3:  # 文の終わりまで3字以下には入れない
                continue
            if c in "、" or (c in "はがをにでともへや" and rest[:1] and rest[:1] not in "、。」）』ー〜・" and re.match(r"[぀-ゟ]", c)):
                if rest[:1] and rest[:1] not in "、。！？」）』":
                    s += "<wbr>"
        out.append(s)
    return "".join(out)

